// Calibrates journey levels with the bot and writes src/levelTable.ts.
// For each level it lowers the pre-filled density until the bot can actually play it, then caps each
// goal at 70% of what the bot reaches. Re-run (npm run levels) after changing rules, pieces or levels.
// Run with: npx vite-node scripts/make-levels.ts

import { writeFileSync } from "node:fs";
import { baseTarget, defaultDensity, goalReached, makeLevel, prefillFor, type GoalKind, type LevelTuning } from "../src/journey";
import { playBot } from "../src/solver";

const LEVELS = 150;
const MIN_MOVES = 25; // the bot must manage at least this many placements for a level to count as playable
const kinds: GoalKind[] = ["score", "lines", "place"];
const table: LevelTuning[] = [];

for (let n = 1; n <= LEVELS; n++) {
  const seed = `j-${n}`;
  let d = defaultDensity(n);
  let r = playBot({ seed, start: prefillFor(n, d), maxMoves: 300 });
  while (r.moves < MIN_MOVES && d > 0.05) {
    d = Math.max(0.05, +(d - 0.03).toFixed(3));
    r = playBot({ seed, start: prefillFor(n, d), maxMoves: 300 });
  }
  const entry: LevelTuning = { d: +d.toFixed(3), s: Math.floor(r.score * 0.7), l: Math.floor(r.lines * 0.7), m: Math.floor(r.moves * 0.7), pm: 0 };
  // How many placements the bot needs to reach this level's final goal: that is the 3-star mark.
  const lv = makeLevel(n, [...table, entry]);
  const goal = playBot({
    seed, start: lv.prefill, maxMoves: 300,
    stop: (b) => goalReached(lv, { score: b.score, lines: b.lines, moves: b.moves }),
  });
  entry.pm = goal.moves;
  table.push(entry);
  if (n <= 10 || n % 25 === 0)
    console.log(`L${n} ${kinds[(n - 1) % 3]} density ${entry.d} | target ${lv.goal.target} (formula ${baseTarget(kinds[(n - 1) % 3]!, n)}) | bot reaches it in ${goal.moves} moves`);
}

const body = table.map((e) => `  { d: ${e.d}, s: ${e.s}, l: ${e.l}, m: ${e.m}, pm: ${e.pm} },`).join("\n");
writeFileSync(
  new URL("../src/levelTable.ts", import.meta.url),
  `// Generated by scripts/make-levels.ts. Do not edit by hand.\nimport type { LevelTuning } from "./journey";\nexport const LEVEL_TABLE: readonly LevelTuning[] = [\n${body}\n];\n`,
);
console.log(`wrote ${table.length} levels`);
